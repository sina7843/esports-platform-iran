import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const required=['Requirements.md','IMPLEMENTATION_DECISIONS.md','CLAUDE.md','README_START_HERE_FA.md','PROJECT_STATUS.md','IMPLEMENTATION_STATUS.md','DECISIONS.md','REQUIREMENTS_TRACEABILITY.md','ESPORTS_ALL_7_PROMPTS_FA.md','prompts/QUICK_START.md','prompts/prompt-manifest.json','prompts/requirement-coverage.json','tools/Copy-EsportsPrompt.ps1','.claude/settings.json',...['01-INSTALL-TOOLS','02-SETUP-PROJECT','03-CHECK-PACKAGE','04-COPY-NEXT-PROMPT','05-START-CLAUDE','06-CREATE-LOCAL-ENV'].map(x=>x+'.cmd')];
for(const p of required) assert.ok(fs.existsSync(path.join(root,p)),`Missing ${p}`);
const manifest=JSON.parse(read('prompts/prompt-manifest.json'));
assert.equal(manifest.prompt_count,7);
assert.equal(manifest.prompts.length,7);
const promptFiles=fs.readdirSync(path.join(root,'prompts')).filter(x=>/^\d{2}-.*\.md$/.test(x)).sort();
assert.equal(promptFiles.length,7);
assert.equal(fs.existsSync(path.join(root,'prompts','slices')),false);
const combined=read('ESPORTS_ALL_7_PROMPTS_FA.md');
assert.equal([...combined.matchAll(/```text\r?\n/g)].length,7);
const status=read('PROJECT_STATUS.md');
for(let i=0;i<7;i++){
 const p=manifest.prompts[i],id=`ESP-${String(i+1).padStart(2,'0')}`;
 assert.equal(p.id,id);
 assert.deepEqual(p.depends_on,i===0?[]:[`ESP-${String(i).padStart(2,'0')}`]);
 assert.ok(p.file.startsWith(`prompts/${String(i+1).padStart(2,'0')}-`));
 const text=read(p.file),blocks=[...text.matchAll(/```text\s*\r?\n([\s\S]+?)\r?\n```/g)];
 assert.equal(blocks.length,1,p.file);
 assert.ok(blocks[0][1].startsWith(id));
 for(const token of ['git rev-list --all --count','Requirements.md','IMPLEMENTATION_DECISIONS.md','REQUIREMENTS_TRACEABILITY.md','06-CREATE-LOCAL-ENV.cmd']) assert.ok(blocks[0][1].includes(token),`${id} lacks ${token}`);
 assert.ok(combined.includes(blocks[0][1]),`${id}: combined copy differs`);
 assert.match(status,new RegExp(`^- \\[[ x]\\] ${id}\\s*$`,'m'));
}
const source=read('Requirements.md');
const ids=[...new Set(source.match(/\b(?:[A-Z]+-\d{3}|AC-\d{2})\b/g))].sort();
const coverage=JSON.parse(read('prompts/requirement-coverage.json'));
assert.equal(coverage.source_sha256,createHash('sha256').update(fs.readFileSync(path.join(root,'Requirements.md'))).digest('hex'));
assert.equal(ids.length,307);
assert.equal(coverage.count,ids.length);
assert.equal(new Set(coverage.requirements.map(x=>x.requirement_id)).size,ids.length);
assert.deepEqual(coverage.requirements.map(x=>x.requirement_id).sort(),ids);
const trace=read('REQUIREMENTS_TRACEABILITY.md');
for(const item of coverage.requirements){
 assert.ok(manifest.prompts.some(p=>p.id===item.primary_prompt),item.requirement_id);
 assert.equal(item.integration_prompt,'ESP-07');
 assert.match(trace,new RegExp(`^\\| ${item.requirement_id} \\| ${item.primary_prompt} \\| ESP-07 \\|`,'m'));
}
const setup=read('tools/Setup-Project.ps1');
assert.ok(setup.includes('prompts\\01-foundation.md'));
assert.ok(setup.includes('.esports-backups'));
assert.ok(setup.includes('gitBashCandidates = @(@('));
const copy=read('tools/Copy-EsportsPrompt.ps1');
assert.ok(copy.includes('-Raw -Encoding UTF8'));
assert.ok(copy.includes('depends_on'));
assert.ok(copy.includes('Set-Clipboard'));
assert.ok(read('04-COPY-NEXT-PROMPT.cmd').includes('Copy-EsportsPrompt.ps1'));
assert.equal(fs.existsSync(path.join(root,'tools/Copy-DragonPrompt.ps1')),false);
const settings=JSON.parse(read('.claude/settings.json'));
assert.deepEqual(Object.keys(settings.hooks),['PreToolUse']);
assert.equal('sandbox' in settings,false);
const attrs=read('.gitattributes');
for(const rule of ['*.yml text eol=lf','*.yaml text eol=lf','Dockerfile text eol=lf','*entrypoint* text eol=lf']) assert.ok(attrs.includes(rule));
const policy=read('IMPLEMENTATION_DECISIONS.md');
assert.ok(policy.includes('RPO<=15min'));
assert.ok(policy.includes('never activate silently in production'));
console.log(`Package validation passed: exactly 7 full prompts, ordered dependencies, identical combined copies, source hash, ${ids.length} unique requirement mappings, UTF-8 copy tool and protected-source setup.`);
